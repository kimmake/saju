def part(c, pts, fill, a=0.5, w=2.2, outline=0.85):
    """면(담채) + 등 쪽 그늘(덧칠) + 끊기며 굵기가 변하는 먹 윤곽."""
    c.wash(pts, fill, alpha=a)
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]; cx, cy = sum(xs) / len(xs), sum(ys) / len(ys)
    h = max(ys) - min(ys)
    back = [(cx + (x - cx) * 0.82, cy + (y - cy) * 0.62 - h * 0.16) for x, y in pts]
    c.wash(back, tuple(int(v * 0.62) for v in fill), alpha=a * 0.42, bleed=3.0, edge=0.1)
    ring = pts + [pts[0], pts[1]]
    k = int(c.rng.integers(0, len(pts)))  # 한 군데는 붓을 떼어 윤곽을 열어 둔다
    c.line(ring[k + 1:] + ring[:k], press=lambda t: w * (0.55 + 0.6 * abs(np.sin(t * 9 + k))), alpha=outline, dry=0.1)


